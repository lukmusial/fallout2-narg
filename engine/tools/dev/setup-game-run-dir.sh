#!/bin/bash
# Prepare a run directory for a macOS build against any installed game folder
# (vanilla, Restoration Project, ...), for hidden --dev-script runs.
#
#   tools/dev/setup-game-run-dir.sh <game dir> <run dir> <build dir> [--hd] [--no-saves]
#
# The game folder is cloned (APFS `cp -c`: instant, no extra space until
# written) without any .app it contains, so the game writes its config, saves
# and maps into the run directory and the installed game is only read.
# <build dir> holds the "Fallout II Community Edition.app" to run (its ce.dat
# is inside the bundle). With --hd, the HD packs generated by tools/hd
# (HD_PACKS_DIR, default out/build/macos/data/hd of this tree: ai,
# scripted and, when made, rpu) are linked into <run dir>/data/hd. With
# --no-saves the game's saves are left out (new-game runs save to slot 1).
#
# Re-running replaces the run directory.

set -euo pipefail

if [[ $# -lt 3 ]]; then
    sed -n 2,14p "$0" >&2
    exit 1
fi

GAME_DIR="$(cd "$1" && pwd)"
RUN_DIR="$2"
BUILD_DIR="$(cd "$3" && pwd)"
HD=0
SAVES=1
for option in "${@:4}"; do
    case "$option" in
    --hd) HD=1 ;;
    --no-saves) SAVES=0 ;;
    *)
        echo "unknown option $option" >&2
        exit 1
        ;;
    esac
done
APP="Fallout II Community Edition.app"
REPO_DIR="$(cd "$(dirname "$0")/../.." && pwd)"
HD_PACKS_DIR="${HD_PACKS_DIR:-$REPO_DIR/out/build/macos/data/hd}"

if [[ ! -f "$GAME_DIR/master.dat" ]]; then
    echo "error: $GAME_DIR/master.dat not found" >&2
    exit 1
fi
if [[ ! -d "$BUILD_DIR/$APP" ]]; then
    echo "error: $BUILD_DIR/$APP not found" >&2
    exit 1
fi

rm -rf "$RUN_DIR"
mkdir -p "$RUN_DIR"
for entry in "$GAME_DIR"/* "$GAME_DIR"/.[!.]*; do
    [[ -e "$entry" ]] || continue
    name="$(basename "$entry")"
    [[ "$name" == *.app ]] && continue
    cp -cR "$entry" "$RUN_DIR/$name"
done
cp -cR "$BUILD_DIR/$APP" "$RUN_DIR/$APP"
if [[ $SAVES -eq 0 ]]; then
    rm -rf "$RUN_DIR/data/SAVEGAME" "$RUN_DIR/data/savegame"
fi

if [[ $HD -eq 1 ]]; then
    mkdir -p "$RUN_DIR/data/hd"
    # rpu: the Restoration Project's own art (tools/hd/mod_pack.py), used
    # after ai by the mixed manifest; optional.
    for pack in ai scripted rpu; do
        if [[ -d "$HD_PACKS_DIR/$pack" ]]; then
            ln -sfn "$HD_PACKS_DIR/$pack" "$RUN_DIR/data/hd/$pack"
        elif [[ "$pack" != rpu ]]; then
            echo "warning: no HD pack $HD_PACKS_DIR/$pack" >&2
        fi
    done
fi

echo "run directory ready: $RUN_DIR"
